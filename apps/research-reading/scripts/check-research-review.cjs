const { chromium } = require('C:/Users/Lenovo/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
const assert = require('node:assert/strict')
;(async () => {
  const browser = await chromium.launch({channel:'msedge',headless:true})
  try {
    const context = await browser.newContext({viewport:{width:1600,height:1000}})
    const page = await context.newPage()
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto('http://127.0.0.1:5174/?view=research')
    await page.locator('.research-review').waitFor()
    assert.equal(await page.locator('.review-point').count(),66)
    await page.screenshot({path:'.local/research-review-desktop.png'})
    await page.getByLabel('一级功能',{exact:true}).selectOption('0')
    await page.getByLabel('二级功能',{exact:true}).selectOption('R2')
    await page.getByLabel('三级功能',{exact:true}).selectOption('R2.9')
    assert.equal(await page.locator('.review-point').count(),1)
    await page.locator('.review-point-details').click()
    assert.match(await page.locator('.review-detail').innerText(),/AI初审 · 不合规/)
    await page.locator('.review-edit select').first().selectOption('待定')
    await page.getByLabel('追加备注').fill('自动验证：复核持久化')
    await page.getByRole('tab',{name:'智能阅读',exact:true}).click()
    await page.getByRole('button',{name:'继续编辑',exact:true}).click()
    assert.equal(await page.getByLabel('追加备注').inputValue(),'自动验证：复核持久化')
    await page.getByRole('button',{name:'保存审核',exact:true}).click()
    await page.reload()
    await page.getByLabel('搜索功能编号或标题').fill('R2.9')
    assert.equal(await page.locator('.review-point').count(),1)
    assert.equal(await page.getByLabel('R2.9 合规状态',{exact:true}).inputValue(),'待定')
    await page.locator('.review-point-details').click()
    assert.match(await page.locator('.review-history').innerText(),/自动验证/)
    await page.locator('.review-back').click()
    await page.getByRole('button',{name:'重置筛选',exact:true}).click()
    await page.getByLabel('评审模式',{exact:true}).selectOption('story')
    assert.equal(await page.locator('.review-point').count(),66)
    const downloadWait = page.waitForEvent('download')
    await page.getByRole('button',{name:'导出',exact:true}).click()
    const download = await downloadWait
    assert.equal(download.suggestedFilename(),'智能科研审核记录.json')
    await page.locator('.research-review input[type=file]').setInputFiles({name:'bad.json',mimeType:'application/json',buffer:Buffer.from('{"version":99}')})
    assert.match(await page.locator('.review-message').innerText(),/不受支持/)
    await page.getByRole('tab',{name:'智能阅读',exact:true}).click()
    assert.equal(await page.locator('.research-review').count(),0)
    assert.equal(await page.locator('.review-point').count(),38)
    const mobile = await context.newPage({viewport:{width:390,height:844}}).catch(()=>context.newPage())
    await mobile.setViewportSize({width:390,height:844})
    await mobile.goto('http://127.0.0.1:5174/?view=research')
    await mobile.getByRole('button',{name:'展开合规评审',exact:true}).click()
    const bounds = await mobile.locator('.research-review').boundingBox()
    assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 390)
    await mobile.screenshot({path:'.local/research-review-mobile.png'})
    assert.deepEqual(errors,[])
    console.log('PASS: 66 points, hierarchy, detail, unsaved guard, persistence, stories, export, invalid import, reading isolation, mobile bounds')
  } finally { await browser.close() }
})().catch(error => {console.error(error);process.exitCode=1})
